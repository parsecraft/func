//! Shell completion scripts, generated from [`cli::COMMANDS`] so they can
//! never drift from the real command line.
//!
//! All three shells behave the same way:
//! - first word: commands, and only commands (scripts run via `func run`, so
//!   they never share this namespace, however many you have)
//! - a command's first argument: whatever its [`Target`] says
//! - everything after a script name: the shell's normal file completion
//!
//! Script names come from `func list --names`, asked fresh on every <Tab>,
//! so a script you just created completes immediately.

use crate::cli::{COMMANDS, Shell, Spec, Target};

pub fn generate(shell: Shell) -> String {
    match shell {
        Shell::Bash => bash(),
        Shell::Zsh => zsh(),
        Shell::Fish => fish(),
    }
}

/// Canonical name followed by aliases: `edit|new|e`.
fn names_with_aliases(spec: &Spec, separator: &str) -> String {
    std::iter::once(spec.name).chain(spec.aliases.iter().copied()).collect::<Vec<_>>().join(separator)
}

fn command_words() -> String {
    COMMANDS.iter().map(|spec| spec.name).collect::<Vec<_>>().join(" ")
}

fn flag_words(spec: &Spec) -> String {
    spec.flags.join(" ")
}

// -- bash ---------------------------------------------------------------------

fn bash() -> String {
    let mut arms = String::new();
    for spec in COMMANDS {
        let pattern = names_with_aliases(spec, "|");
        let flags = flag_words(spec);
        let body = match spec.target {
            Target::None => format!("_func_flags '{flags}'"),
            Target::Script => {
                format!("_func_flags '{flags}' || (( positional == 0 )) && _func_complete_scripts")
            }
            Target::Scripts => format!("_func_flags '{flags}' || _func_complete_scripts"),
            Target::ScriptOrFile => format!(
                "_func_flags '{flags}' || {{ (( positional == 0 )) && _func_complete_scripts_or_files || _func_files; }}"
            ),
            Target::Shell => {
                "(( positional == 0 )) && COMPREPLY=( $(compgen -W \"bash zsh fish\" -- \"$cur\") )"
                    .to_string()
            }
            Target::Command => format!(
                "(( positional == 0 )) && COMPREPLY=( $(compgen -W \"{}\" -- \"$cur\") )",
                command_words()
            ),
        };
        arms.push_str(&format!("        {pattern}) {body} ;;\n"));
    }

    format!(
        r#"# bash completion for func. Generated by `func completions bash`.
# Install: add `eval "$(func completions bash)"` to ~/.bashrc

_func_scripts() {{ func list --names 2>/dev/null; }}

_func_complete_scripts() {{
    COMPREPLY=( $(compgen -W "$(_func_scripts)" -- "$cur") )
}}

_func_files() {{
    COMPREPLY=( $(compgen -f -- "$cur") )
}}

# Where a script is expected: saved scripts and .rs files, never every file.
# Once the word looks like a path (./x, ../x, dir/x), offer directories to walk through, and .rs files.
_func_complete_scripts_or_files() {{
    local IFS=$'\n'
    if [[ $cur == */* || $cur == .* ]]; then
        COMPREPLY=( $(compgen -d -S / -- "$cur") $(compgen -f -X '!*.rs' -- "$cur") )
        type compopt &>/dev/null && compopt -o nospace
    else
        COMPREPLY=( $(compgen -W "$(_func_scripts)" -- "$cur") $(compgen -f -X '!*.rs' -- "$cur") )
    fi
    return 0 # "no match" must stay "no match", never fall back to listing every file
}}

# Completes flags when the word being typed starts with "-". Succeeds if it did.
_func_flags() {{
    [[ $cur == -* ]] || return 1
    COMPREPLY=( $(compgen -W "$1" -- "$cur") )
}}

_func() {{
    local cur=${{COMP_WORDS[COMP_CWORD]}} cmd=${{COMP_WORDS[1]}} i positional=0
    COMPREPLY=()

    if (( COMP_CWORD == 1 )); then
        COMPREPLY=( $(compgen -W "{commands}" -- "$cur") )
        return
    fi

    for (( i = 2; i < COMP_CWORD; i++ )); do
        [[ ${{COMP_WORDS[i]}} == -* ]] || (( positional++ ))
    done

    case $cmd in
{arms}        *) ;;
    esac

    # After a script name the arguments are the script's: use normal file completion.
    if (( positional > 0 )) && [[ $cmd == @(run|r|test|t) ]]; then
        type compopt &>/dev/null && compopt -o default
    fi
}}

complete -F _func func
"#,
        commands = command_words(),
        arms = arms,
    )
}

// -- zsh ----------------------------------------------------------------------

fn zsh_escape(text: &str) -> String {
    text.replace('\\', "\\\\").replace(':', "\\:").replace('\'', "'\\''")
}

fn zsh() -> String {
    let described: String = COMMANDS
        .iter()
        .map(|spec| format!("        '{}:{}'\n", spec.name, zsh_escape(spec.summary)))
        .collect();

    let mut arms = String::new();
    for spec in COMMANDS {
        let pattern = names_with_aliases(spec, "|");
        let flags = flag_words(spec);
        let body = match spec.target {
            Target::None => format!("_func_flags {flags}"),
            Target::Script => format!("_func_flags {flags} || (( positional == 0 )) && _func_scripts"),
            Target::Scripts => format!("_func_flags {flags} || _func_scripts"),
            Target::ScriptOrFile => {
                // The script position offers scripts and .rs files; after it, the script's own arguments.
                format!(
                    "_func_flags {flags} || {{ if (( positional == 0 )); then _func_scripts; _files -g '*.rs'; else _files; fi }}"
                )
            }
            Target::Shell => "(( positional == 0 )) && compadd -- bash zsh fish".to_string(),
            Target::Command => {
                "(( positional == 0 )) && _describe -t commands 'command' commands".to_string()
            }
        };
        arms.push_str(&format!("        {pattern}) {body} ;;\n"));
    }

    format!(
        r#"#compdef func
# zsh completion for func. Generated by `func completions zsh`.
# Install: func completions zsh > ~/.zfunc/_func   (with ~/.zfunc in $fpath, before compinit)
#      or: eval "$(func completions zsh)"           (after compinit)

_func_scripts() {{
    local -a scripts
    scripts=( ${{(f)"$(func list --names 2>/dev/null)"}} )
    (( ${{#scripts}} )) && _describe -t scripts 'script' scripts
}}

# Completes flags when the word being typed starts with "-". Succeeds if it did.
_func_flags() {{
    [[ $words[CURRENT] == -* ]] || return 1
    (( $# )) && compadd -- "$@"
    return 0
}}

_func() {{
    local -a commands
    commands=(
{described}    )

    if (( CURRENT == 2 )); then
        _describe -t commands 'command' commands
        return
    fi

    local -i positional=0 i
    for (( i = 3; i < CURRENT; i++ )); do
        [[ $words[i] == -* ]] || (( positional++ ))
    done

    case $words[2] in
{arms}        *) ;;
    esac
}}

if [[ ${{funcstack[1]}} == _func ]]; then
    _func "$@"
else
    compdef _func func
fi
"#,
        described = described,
        arms = arms,
    )
}

// -- fish ---------------------------------------------------------------------

fn fish_escape(text: &str) -> String {
    text.replace('\\', "\\\\").replace('\'', "\\'")
}

fn fish() -> String {
    let mut out = String::from(
        r#"# fish completion for func. Generated by `func completions fish`.
# Install: func completions fish > ~/.config/fish/completions/func.fish

function __func_scripts
    func list --names 2>/dev/null
end

# True while completing the first argument of one of the given commands
# (flags in between do not count as arguments).
function __func_at_first_arg
    set -l tokens (commandline -opc)
    test (count $tokens) -ge 2; or return 1
    contains -- $tokens[2] $argv; or return 1
    set -l n 0
    for token in $tokens
        set n (math $n + 1)
        test $n -ge 3; or continue
        string match -q -- '-*' $token; or return 1
    end
    return 0
end

# The path being typed, narrowed to what a script argument can be: .rs files,
# and folders to walk through once the word looks like a path (./x, dir/x).
# Built from plain `ls` and `string` on purpose: nothing here can offer "every file".
function __func_rs_paths
    set -l word (commandline -ct)
    set -l dir (string replace -r '[^/]*$' '' -- "$word")
    set -l prefix (string replace -r '^.*/' '' -- "$word")
    set -l base $dir
    test -n "$base"; or set base .
    set -l path_like false
    string match -q -r '^\.|/' -- "$word"; and set path_like true
    set -l length (string length -- "$prefix")

    for entry in (command ls -1Ap -- $base 2>/dev/null)
        if test $length -gt 0
            test (string sub -l $length -- $entry) = "$prefix"; or continue
        end
        if string match -q '.*' -- $entry; and test -z "$prefix"
            continue # hidden files only when asked for
        end
        if string match -q '*.rs' -- $entry
            echo $dir$entry
        else if test $path_like = true; and string match -q '*/' -- $entry
            echo $dir$entry
        end
    end
end

# True once a first argument (the script) has been typed: what follows belongs to the script.
function __func_past_first_arg
    set -l tokens (commandline -opc)
    test (count $tokens) -ge 2; and contains -- $tokens[2] $argv; or return 1
    set -l n 0
    set -l positional 0
    for token in $tokens
        set n (math $n + 1)
        test $n -ge 3; or continue
        string match -q -- '-*' $token; or set positional (math $positional + 1)
    end
    test $positional -ge 1
end

# True while completing any argument of one of the given commands.
function __func_at_any_arg
    set -l tokens (commandline -opc)
    test (count $tokens) -ge 2; and contains -- $tokens[2] $argv
end

complete -c func -f

"#,
    );

    // Commands, and saved scripts, as the first word.
    for spec in COMMANDS {
        out.push_str(&format!(
            "complete -c func -n __fish_use_subcommand -a '{}' -d '{}'\n",
            spec.name,
            fish_escape(spec.summary)
        ));
    }
    out.push('\n');

    for spec in COMMANDS {
        let names = names_with_aliases(spec, " ");

        for flag in spec.flags {
            let option = match flag.strip_prefix("--") {
                Some(long) => format!("-l {long}"),
                None => format!("-s {}", &flag[1..]),
            };
            out.push_str(&format!("complete -c func -n '__func_at_any_arg {names}' {option}\n"));
        }

        match spec.target {
            Target::None => {}
            Target::Script => out.push_str(&format!(
                "complete -c func -n '__func_at_first_arg {names}' -a '(__func_scripts)'\n"
            )),
            Target::Scripts => out.push_str(&format!(
                "complete -c func -n '__func_at_any_arg {names}' -a '(__func_scripts)'\n"
            )),
            Target::ScriptOrFile => out.push_str(&format!(
                "complete -c func -n '__func_at_first_arg {names}' -a '(__func_scripts)'\n\
                 complete -c func -n '__func_at_first_arg {names}' -a '(__func_rs_paths)'\n\
                 complete -c func -n '__func_past_first_arg {names}' -F\n"
            )),
            Target::Shell => out
                .push_str(&format!("complete -c func -n '__func_at_first_arg {names}' -a 'bash zsh fish'\n")),
            Target::Command => out.push_str(&format!(
                "complete -c func -n '__func_at_first_arg {names}' -a '{}'\n",
                command_words()
            )),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn commands_with(target: fn(Target) -> bool) -> impl Iterator<Item = &'static Spec> {
        COMMANDS.iter().filter(move |spec| target(spec.target))
    }

    const SHELLS: [Shell; 3] = [Shell::Bash, Shell::Zsh, Shell::Fish];

    #[test]
    fn every_command_appears_in_every_shell() {
        for shell in SHELLS {
            let script = generate(shell);
            for spec in COMMANDS {
                assert!(script.contains(spec.name), "{shell:?} completions lack `{}`", spec.name);
            }
        }
    }

    #[test]
    fn every_flag_appears_in_every_shell() {
        for shell in SHELLS {
            let script = generate(shell);
            for spec in COMMANDS {
                for flag in spec.flags {
                    let needle = flag.trim_start_matches('-');
                    assert!(script.contains(needle), "{shell:?} completions lack `{flag}`");
                }
            }
        }
    }

    #[test]
    fn script_names_are_asked_for_at_tab_time() {
        for shell in SHELLS {
            assert!(generate(shell).contains("func list --names"));
        }
    }

    #[test]
    fn targets_pick_the_right_commands() {
        let with_files: Vec<_> = commands_with(|t| t == Target::ScriptOrFile).map(|s| s.name).collect();
        assert_eq!(with_files, ["run", "test", "check", "install"]);
    }

    #[test]
    fn fish_never_forces_files_at_the_script_position() {
        let fish = generate(Shell::Fish);
        assert!(fish.contains("__func_rs_paths"));
        assert!(!fish.contains("__fish_complete_suffix"));
        // `-F` (force files) may only follow a script name, where the arguments are the script's.
        for line in fish.lines().filter(|line| line.ends_with(" -F")) {
            assert!(line.contains("__func_past_first_arg"), "{line}");
        }
    }

    #[test]
    fn zsh_descriptions_escape_colons() {
        assert_eq!(zsh_escape("a: b"), "a\\: b");
    }
}
