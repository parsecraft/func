#!/bin/sh
# Install func: build it, copy the binary, add shell completions.
#
#   ./install.sh                       from a checkout: install to ~/.local/bin
#   ./install.sh --prefix /usr/local   install to /usr/local/bin (may need sudo)
#   ./install.sh --no-completions      skip the shell completion files
#   curl -fsSL https://raw.githubusercontent.com/parsecraft/func/main/install.sh | sh
#   curl -fsSL .../install.sh | sh -s -- --prefix /usr/local
#
# Run from outside a checkout, it fetches the source first (needs git and cargo).
# FUNC_REPO and FUNC_REF choose another repository or branch/tag.
# Everything it touches is printed. Undo it with ./uninstall.sh.

set -eu

repo_url="${FUNC_REPO:-https://github.com/parsecraft/func}"
repo_ref="${FUNC_REF:-main}"
bin_dir="${HOME:-}/.local/bin"
completions=yes

say() { printf '%s\n' "$*"; }
die() {
    printf '\n-- INSTALL FAILED ----------------------------------------------------------\n\n%s\n\n' "$*" >&2
    exit 1
}

while [ $# -gt 0 ]; do
    case $1 in
        --prefix)
            [ $# -ge 2 ] || die "--prefix needs a directory, for example: ./install.sh --prefix /usr/local"
            bin_dir="$2/bin"
            shift 2
            ;;
        --no-completions) completions=no; shift ;;
        -h | --help)
            sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'
            exit 0
            ;;
        *) die "I do not know the option \`$1\`.

Run ./install.sh --help to see what I understand." ;;
    esac
done

[ -n "${HOME:-}" ] || [ "$bin_dir" != "/.local/bin" ] || die "\$HOME is not set, so I do not know where to install.

Tell me explicitly: ./install.sh --prefix <directory>"

command -v cargo >/dev/null 2>&1 || die "I need Rust to build func, but \`cargo\` is not on your PATH.

Install it from https://rustup.rs, open a new terminal, and run this again."

# Where the source is. A piped install has no checkout beside it (and `$0` is just
# "sh"), so look for func's own Cargo.toml rather than trusting the current directory.
is_func_checkout() { [ -f "$1/Cargo.toml" ] && grep -q '^name = "func"$' "$1/Cargo.toml"; }

here=$(cd "$(dirname "$0")" 2>/dev/null && pwd) || here=""
if ! is_func_checkout "$here"; then
    command -v git >/dev/null 2>&1 || die "I need git to fetch func's source, but \`git\` is not on your PATH.

Install git, or download the repository by hand and run ./install.sh inside it."
    tmp=$(mktemp -d)
    trap 'rm -rf "$tmp"' EXIT
    trap 'exit 1' HUP INT TERM PIPE # signals skip the EXIT trap unless we exit ourselves
    say "Fetching func from $repo_url ($repo_ref)..."
    git clone --quiet --depth 1 --branch "$repo_ref" "$repo_url" "$tmp/func" ||
        die "I could not fetch $repo_url (branch or tag: $repo_ref).

Check your connection, or clone it yourself and run ./install.sh inside."
    here="$tmp/func"
fi

say "Building func (release)..."
(cd "$here" && cargo build --release --quiet) || die "The build failed. The compiler output is above."

mkdir -p "$bin_dir" || die "I could not create $bin_dir."
# Copy then rename, so replacing a running func cannot fail halfway.
if ! { cp "$here/target/release/func" "$bin_dir/.func.partial" && mv -f "$bin_dir/.func.partial" "$bin_dir/func"; }; then
    die "I could not write to $bin_dir.

If it needs administrator rights, use: sudo ./install.sh --prefix /usr/local"
fi
say "  installed  $bin_dir/func"

# Completions are generated by the binary we just built, so they always match it.
install_completion() { # shell, destination
    mkdir -p "$(dirname "$2")"
    "$bin_dir/func" completions "$1" >"$2"
    say "  installed  $2"
}

if [ "$completions" = yes ]; then
    data="${XDG_DATA_HOME:-${HOME:-}/.local/share}"
    config="${XDG_CONFIG_HOME:-${HOME:-}/.config}"
    command -v bash >/dev/null 2>&1 && install_completion bash "$data/bash-completion/completions/func"
    command -v fish >/dev/null 2>&1 && install_completion fish "$config/fish/completions/func.fish"
    if command -v zsh >/dev/null 2>&1; then
        install_completion zsh "$data/zsh/site-functions/_func"
        zsh_note="yes"
    fi
fi

say ""
say "Done. Try it:  func edit hello"

case ":$PATH:" in
    *":$bin_dir:"*) ;;
    *) say ""
       say "Note: $bin_dir is not on your PATH. Add this to your shell profile:"
       say "    bash/zsh:  export PATH=\"$bin_dir:\$PATH\""
       say "    fish:      fish_add_path $bin_dir" ;;
esac

if [ "${zsh_note:-}" = yes ]; then
    say ""
    say "zsh: add this to ~/.zshrc, before compinit, to enable completions:"
    say "    fpath=($data/zsh/site-functions \$fpath)"
fi
